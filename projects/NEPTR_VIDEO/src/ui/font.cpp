int cellFor(char c) {
    if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
    if (c < kFirst || c > kLast) return 0;  // space, not a tofu box
    return c - kFirst;
}

std::vector<uint8_t> buildAtlas() {
    std::vector<uint8_t> px(static_cast<size_t>(atlasWidth()) * atlasHeight(), 0);
    const int stride = atlasWidth();

    for (int g = 0; g < kCount; ++g) {
        for (int col = 0; col < kGlyphW; ++col) {
            uint8_t bits = kGlyphs[g][col];
            for (int row = 0; row < kGlyphH; ++row) {
                if (bits & (1u << row)) {
                    px[static_cast<size_t>(row) * stride + g * kCellW + col] = 255;
                }
            }
        }
    }

    // The solid cell. Filled edge to edge so a rectangle drawn from it has no
    // seam, whatever it is scaled to.
    for (int row = 0; row < kCellH; ++row) {
        for (int col = 0; col < kCellW; ++col) {
            px[static_cast<size_t>(row) * stride + kSolidCell * kCellW + col] = 255;
        }
    }
    return px;
}

