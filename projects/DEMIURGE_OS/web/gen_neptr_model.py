#!/usr/bin/env python3
"""Generate web/neptr_model.py from the on-device pygame UI's source.

The web UI and the pygame UI must expose the SAME instrument: same 20 menus,
same slots, same params, same encoder CCs, same arming toggles. Rather than
hand-copying ~250 rows of tables (which is how two UIs drift apart), this
lifts the literal tables straight out of `neptrPhase4_UI.py` with `ast` and
writes a stdlib-only module the web server imports.

Same idea, one level up, as the NEPTR repo's own
`scripts/gen_param_cc_map.py`, which lifts PARAM_CC out of the .orc sources:
the orc is the truth for the engine, the pygame UI is the truth for the
instrument's presentation, and nothing downstream is typed by hand.

    python3 web/gen_neptr_model.py [PATH_TO_NEPTR_phase4] > web/neptr_model.py

Re-run it after any menu/effect/param change in the pygame UI. The web test
suite asserts the committed module still matches the source it came from
whenever that source is reachable, so drift shows up as a test failure rather
than as a fader that edits the wrong effect.
"""

import ast
import os
import sys

DEFAULT_SRC = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
    "NEPTR phase4")

# Names lifted verbatim. Everything here is a plain literal in the pygame UI.
WANTED = [
    "MENU_COUNT", "MENUS",
    "_ROW_BTN_LOGICAL", "_LOOPER_BTN_LOGICAL", "_PHYS_FOR_BTN", "_PHYS_FOR_ROT",
    "PARAM_CC", "EFFECT_PARAMS",
    "TRM_MODES", "BLP_CHARS", "HAB_REC", "DLY_MODES", "PLL_INTERVALS",
    "FBK_HARMS", "RPT_LENS", "TDL_HEADS",
    "SHM_INTERVALS", "STEP_LABELS", "STEP_SCALE",
    "BASS_PRESETS", "GORCORE_PRESETS", "GORCORE_SLOT_TO_PRESET",
    "SLOT_TO_PRESET",
    "EXPR_CC", "PARAM_BURST", "PARAM_DEADBAND",
]


def lift(src_path):
    with open(src_path) as fh:
        tree = ast.parse(fh.read())
    out = {}
    # Two shapes appear: plain literals, and literals that reference an
    # earlier literal by name (STEP_LABELS keys its lists as TRM_MODES etc.).
    # Evaluate in order against what has already been lifted, so the second
    # shape resolves without executing anything else in the module.
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            if isinstance(target, ast.Name) and target.id in WANTED:
                try:
                    out[target.id] = ast.literal_eval(node.value)
                except ValueError:
                    try:
                        out[target.id] = eval(          # noqa: S307 (dev tool)
                            compile(ast.Expression(node.value), src_path,
                                    "eval"),
                            {"__builtins__": {}}, dict(out))
                    except Exception:
                        pass
    missing = [n for n in WANTED if n not in out]
    if missing:
        raise SystemExit("could not lift: %s" % ", ".join(missing))
    return out


def fmt(value, indent=0):
    """Deterministic repr: dicts sorted by key so regenerating is a no-op."""
    pad = " " * indent
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = sorted(value.items(), key=lambda kv: (str(type(kv[0])), kv[0]))
        body = "".join("%s    %r: %s,\n" % (pad, k, fmt(v, indent + 4))
                       for k, v in items)
        return "{\n%s%s}" % (body, pad)
    if isinstance(value, list):
        if not value or not isinstance(value[0], (list, dict, tuple)):
            return repr(value)
        body = "".join("%s    %s,\n" % (pad, fmt(v, indent + 4)) for v in value)
        return "[\n%s%s]" % (body, pad)
    return repr(value)


HEADER = '''"""NEPTR instrument model — GENERATED by web/gen_neptr_model.py.

Do not hand-edit. Every table here is lifted from the on-device pygame UI
(`NEPTR phase4/neptrPhase4_UI.py`) so the web UI and the panel expose the
same instrument by construction. Regenerate after any menu/effect/param
change there:

    python3 web/gen_neptr_model.py > web/neptr_model.py

Source of each table, and why it matters here:

* MENUS          20 menus x 5 slots, drawn leftmost-first = hardware slot4
                 first. The web keeps that order so panel muscle memory
                 transfers to the phone.
* PARAM_CC       {(code, param): (LOGICAL rotation CC, arming toggle id)},
                 itself generated from the .orc sources. A param absent here
                 has NO encoder path in the engine: its fader is unavailable,
                 not broken.
* _PHYS_FOR_*    logical -> PHYSICAL CC. The engine's handler_remap.orc
                 permutes physical encoder CCs into logical ones, so every
                 UI (Teensy, touch, web) emits the PHYSICAL numbers.
"""
'''

FOOTER = '''

# ── derived (same derivations the pygame UI makes) ───────────────────────────

ALL_EFFECTS = {}
for _menu in MENUS:
    for _code, _label in _menu["effects"]:
        ALL_EFFECTS[_code] = _label


def _menu_index(prefix):
    for i, m in enumerate(MENUS):
        if any(code.startswith(prefix) and code[len(prefix):].isdigit()
               for code, _ in m["effects"]):
            return i
    return -1


NAM_MENU = _menu_index("nam")
IR_MENU = _menu_index("ir")
LOOPER_MENU = next((i for i, m in enumerate(MENUS)
                    if m["name"] == "LOOPER"), -1)
PRESET_MENU = next((i for i, m in enumerate(MENUS)
                    if m["name"] == "PRESETS"), -1)
SURF_PRESETS = MENUS[0]["effects"] if MENUS else []

# Menu paging: the engine's own prev/next button CCs (physical). The /menu
# echo drives the view change, exactly as a hardware press would.
MENU_PREV_CC = 76
MENU_NEXT_CC = 74

# ch16 CC102 = "UI sync request": the engine answers with a full OSC state
# snapshot. Same message the pygame UI sends on (re)start.
CC_UI_SYNC = 102
UTILITY_CHANNEL = 15          # 0-based == MIDI ch16

# Every physical CC this UI is ever allowed to emit on ch1. The server
# refuses anything else, so a malformed request can never reach an
# unintended engine control.
ALLOWED_PHYS_CC = (frozenset(_PHYS_FOR_BTN.values())
                   | frozenset(_PHYS_FOR_ROT.values())
                   | {MENU_PREV_CC, MENU_NEXT_CC, EXPR_CC})


def slot_button_cc(menu_idx, row):
    """PHYSICAL button CC that toggles `row` (0-4) of `menu_idx`."""
    if not (0 <= menu_idx < len(MENUS)) or not (0 <= row < 5):
        return None
    logical = (_LOOPER_BTN_LOGICAL if menu_idx == LOOPER_MENU
               else _ROW_BTN_LOGICAL)[row]
    return _PHYS_FOR_BTN[logical]


def hw_slot(menu_idx, row):
    """Hardware slot number the row maps to (labelling only)."""
    if menu_idx == LOOPER_MENU:
        return row
    return 4 - row


def param_rot_cc(code, param):
    """(physical rotation CC, arming toggle id), or None when the engine has
    no encoder path for this param. The rotation dispatch is gkLastToggle-
    keyed, so a pulse only edits this effect while the engine's last-toggled
    effect IS this one — the caller gates on that toggle id."""
    if code.startswith("nam") and code[3:].isdigit():
        code = "nam"                       # rows share the two gain params
    hit = PARAM_CC.get((code, param))
    if hit is None:
        return None
    logical, toggle_id = hit
    return _PHYS_FOR_ROT[logical], toggle_id


def step_labels(code, param):
    """Text labels for a stepped param, or None if it reads as a number."""
    return STEP_LABELS.get((code, param))


def osc_addr(code, param):
    """The OSC address the engine publishes this param on."""
    return "/%s_%s" % (code, param)


def value_format(lo, hi):
    """Integer display for big or whole-stepped ranges; otherwise 2dp.
    Mirrors the pygame UI's _value_fmt so both surfaces read a value the
    same way."""
    span = hi - lo
    if span >= 50 or (isinstance(lo, int) and isinstance(hi, int)
                      and 1 < span <= 30):
        return 0
    return 2


def unavailable_params():
    """[(code, param)] with no encoder path in the engine — every fader the
    UI must show as unavailable rather than let it look live. Ordered as the
    menus draw them so the list reads like the instrument."""
    seen, out = set(), []
    for menu in MENUS:
        for code, _label in menu["effects"]:
            if code in seen:
                continue
            seen.add(code)
            for entry in EFFECT_PARAMS.get(code, []):
                if param_rot_cc(code, entry[0]) is None:
                    out.append((code, entry[0]))
    return out


def describe():
    """The whole instrument as JSON-ready data: one payload the browser
    fetches once and keeps. Live values ride the status frame instead."""
    menus = []
    for idx, menu in enumerate(MENUS):
        slots = []
        for row, (code, label) in enumerate(menu["effects"]):
            params = []
            for entry in EFFECT_PARAMS.get(code, []):
                name, plabel, lo, hi = entry
                hit = param_rot_cc(code, name)
                params.append({
                    "name": name, "label": plabel,
                    "lo": lo, "hi": hi,
                    "decimals": value_format(lo, hi),
                    "addr": osc_addr(code, name),
                    "cc": (hit[0] if hit else None),
                    "toggle": (hit[1] if hit else None),
                    "steps": step_labels(code, name),
                    "scale": STEP_SCALE.get((code, name)),
                })
            slots.append({
                "row": row, "code": code, "label": label,
                "hw": hw_slot(idx, row),
                "cc": slot_button_cc(idx, row),
                "empty": code == "\\u2014",
                "params": params,
            })
        menus.append({"index": idx, "name": menu["name"], "slots": slots,
                      "looper": idx == LOOPER_MENU,
                      "presets": idx == PRESET_MENU})
    return {
        "menus": menus,
        "expr_cc": EXPR_CC,
        "looper_menu": LOOPER_MENU,
        "preset_menu": PRESET_MENU,
        "nam_menu": NAM_MENU,
        "ir_menu": IR_MENU,
        "preset_banks": [
            [list(p) for p in SURF_PRESETS],
            [list(p) for p in BASS_PRESETS],
            [list(p) for p in GORCORE_PRESETS],
        ],
        "gorcore_slot_preset": {str(k): v
                                for k, v in GORCORE_SLOT_TO_PRESET.items()},
        "burst": PARAM_BURST,
        "deadband": PARAM_DEADBAND,
    }
'''


def main(argv):
    src_root = argv[1] if len(argv) > 1 else DEFAULT_SRC
    src = os.path.join(src_root, "neptrPhase4_UI.py")
    data = lift(src)
    print(HEADER)
    for name in WANTED:
        print("%s = %s\n" % (name, fmt(data[name])))
    print(FOOTER.rstrip())
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
