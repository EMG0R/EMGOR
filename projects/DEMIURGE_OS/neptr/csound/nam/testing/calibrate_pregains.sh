#!/bin/bash
# calibrate_pregains.sh — find per-profile pre-NAM gain (dB) for unity
# through-amp loudness at the interface green-before-yellow reference
# (-6.9 dBFS peak multi-tone). Writes testing/nam_pregain.conf.
#
# Requires the NAM plugin .so (pass path via NAM_SO env or default below)
# and csound 6.18. Runs profiles in parallel (5 jobs), iterations within
# a profile are sequential fixed-point: g += (rmsIn - rmsOut), halved on
# oscillation, |err| <= 0.15 dB converges.

set -u
cd "$(dirname "$0")"

NAM_SO="${NAM_SO:-/private/tmp/claude-501/-Users-emgor-Documents--EMGOR-SYNTH-------2026NEW-DEMIURGE-OS/2c35e0bb-0438-4f0a-adee-e4c2e530efdd/scratchpad/nam-build/csound-nam.so}"
CSD="nam_pregain_calibrate.csd"
TOL=0.15
MAXIT=8

mkdir -p logs results
rm -f results/*.res

# Never auto-load AND --opcode-lib together (double registration crash).
if ls /usr/local/lib/csound/plugins64/csound-nam.so >/dev/null 2>&1; then
    OPCLIB=""
    echo "[cal] using auto-loaded system plugin"
else
    OPCLIB="--opcode-lib=$NAM_SO"
    echo "[cal] using $NAM_SO"
fi

PROFILES=()
while IFS= read -r f; do PROFILES+=("$f"); done < <(ls measure_profiles/*.nam | sort)
COUNT=${#PROFILES[@]}
if [ "$COUNT" -lt 1 ]; then
    echo "[cal] FATAL: no .nam profiles in measure_profiles/" >&2
    exit 1
fi
OUT_CONF="${OUT_CONF:-nam_pregain.conf}"
echo "[cal] $COUNT profiles -> $OUT_CONF"

run_one () {  # $1=idx $2=pregain_db -> prints "IN OUT DIFF" or "FAIL"
    local i="$1" g="$2" log="logs/p${1}_g${2}.log"
    csound -n -m0 -+msg_color=false $OPCLIB "--omacro:PREGAIN_DB=$g" "--omacro:PIDX=$i" "$CSD" >"$log" 2>&1
    local in out diff
    in=$(grep -m1 "RMS_IN_DB="  "$log" | cut -d= -f2)
    out=$(grep -m1 "RMS_OUT_DB=" "$log" | cut -d= -f2)
    diff=$(grep -m1 "DIFF_DB="   "$log" | cut -d= -f2)
    local base; base=$(basename "${PROFILES[$i]}" .nam)
    if ! grep -q "Loaded profile \[$i\] $base" "$log"; then
        echo "FAIL no-load"; return
    fi
    if [ -z "$in" ] || [ -z "$out" ] || [ "$in" = "NAN" ]; then
        echo "FAIL no-rms"; return
    fi
    # passthrough guard: model output must differ from its input
    if awk -v d="$diff" 'BEGIN{exit !(d < -50)}'; then
        echo "FAIL passthrough"; return
    fi
    echo "$in $out $diff"
}

calibrate_profile () {  # $1 = index
    local i="$1"
    local base; base=$(basename "${PROFILES[$i]}" .nam)
    local g=0.0 preverr=999 it=0 status=FAIL in=0 out=0
    while [ "$it" -lt "$MAXIT" ]; do
        it=$((it+1))
        local r; r=$(run_one "$i" "$g")
        if [[ "$r" == FAIL* ]]; then
            status="ERROR(${r#FAIL })"; break
        fi
        in=$(echo "$r"  | awk '{print $1}')
        out=$(echo "$r" | awk '{print $2}')
        local err; err=$(awk -v a="$in" -v b="$out" 'BEGIN{printf "%.3f", a-b}')
        if awk -v e="$err" -v t="$TOL" 'BEGIN{exit !((e<0?-e:e) <= t)}'; then
            status=OK; break
        fi
        # oscillation: sign flip with non-shrinking magnitude -> half step
        local step="$err"
        if awk -v e="$err" -v p="$preverr" 'BEGIN{exit !((e*p < 0) && ((e<0?-e:e) >= (p<0?-p:p)*0.9))}'; then
            step=$(awk -v e="$err" 'BEGIN{printf "%.3f", e/2}')
        fi
        preverr="$err"
        g=$(awk -v g="$g" -v s="$step" 'BEGIN{printf "%.2f", g+s}')
        # clamp
        if awk -v g="$g" 'BEGIN{exit !(g < -30)}'; then g="-30.00"; fi
        if awk -v g="$g" 'BEGIN{exit !(g > 15)}';  then g="15.00";  fi
    done
    printf "%s|%s|%s|%s|%s|%s\n" "$base" "$g" "$in" "$out" "$it" "$status" > "results/p${i}.res"
    echo "[cal] [$i] $base -> $g dB ($status, $it iters)"
}

# parallel across profiles, max 5 jobs
for i in $(seq 0 $((COUNT-1))); do
    calibrate_profile "$i" &
    while [ "$(jobs -rp | wc -l)" -ge 5 ]; do sleep 1; done
done
wait

# assemble conf + table
{
  echo "# pre-NAM gain (dB) per profile for unity"
  echo "# through-amp level at the interface green-before-yellow reference"
  echo "# (-6.9 dBFS peak / -13.1 dBFS RMS multi-tone: 110+220+440 Hz)."
  echo "# Generated by testing/calibrate_pregains.sh. Output gain is unity;"
  echo "# a profile listed here overrides input_pad_db + loudness_norm."
} > "$OUT_CONF"

printf "\n%-38s %10s %10s %10s %5s %s\n" "profile" "pregain_dB" "in_dB" "out_dB" "iters" "status"
for i in $(seq 0 $((COUNT-1))); do
    IFS='|' read -r base g in out it status < "results/p${i}.res"
    grounded=$(awk -v g="$g" 'BEGIN{printf "%.1f", g}')
    echo "$base = $grounded" >> "$OUT_CONF"
    printf "%-38s %10s %10s %10s %5s %s\n" "$base" "$grounded" "$in" "$out" "$it" "$status"
done
echo
echo "[cal] wrote $OUT_CONF"
