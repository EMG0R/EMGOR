#!/usr/bin/env python3
"""Generate op_tables.h (stdlib only): sine, exp2 mantissa, TPT one-pole G vs relative cutoff.
Usage: .venv/bin/python src/common/gen_tables.py > src/common/op_tables.h"""
import math

def arr(name, vals, ctype, per=12):
    s = f"static const {ctype} {name}[{len(vals)}] = {{\n"
    for i in range(0, len(vals), per):
        s += "    " + ", ".join(str(v) for v in vals[i:i+per]) + ",\n"
    return s + "};\n"

print("/* GENERATED by gen_tables.py -- do not edit */")
print("#ifndef OP_TABLES_H\n#define OP_TABLES_H\n#include <stdint.h>")
# sine: 256 points + wrap
print(arr("op_sin_tab", [round(32767 * math.sin(2 * math.pi * i / 256)) for i in range(257)], "int16_t"))
# exp2 mantissa 2^(i/256) in Q15 (32768..65536) ; 257 entries
print(arr("op_exp2_tab", [round(32768 * 2 ** (i / 256)) for i in range(257)], "uint32_t", 8))
# TPT one-pole G = g/(1+g), g = tan(pi*fc/sr), fc = sr/2 * 2^(-r/12), r in 1/8 semitone steps.
# r < 1.5 semitones clamped (fc <= ~0.45 sr).
N = 12 * 14 * 8
vals = []
for i in range(N):
    r = max(i / 8.0, 1.5)
    x = math.pi * 0.5 * 2 ** (-r / 12)
    g = math.tan(x)
    vals.append(round(32768 * g / (1 + g)))
print(arr("op_g_tab", vals, "uint16_t"))
print(f"#define OP_G_TAB_N {N}")
print("#endif")
