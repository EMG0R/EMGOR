#!/usr/bin/env python3
"""Generates ofp_gain_tab.c (run with the project .venv python; plain math only, no numpy).
Position axis: pos = g + 100, g in -100..+100 (0 = unity). Knob axis: volume byte 0..255 -> pos."""
import math, sys

KNOB_LO, KNOB_HI, KNOB_C, KNOB_DEAD = 4, 251, 128, 6      # calibration constants: see README (UNVERIFIED until the probe reads the knob)
CEIL_DB = -0.5                                           # hard ceiling
CEIL = 10 ** (CEIL_DB / 20)
DRIVE_DB_MAX = 24.0                                      # pre-gain at +100
Q23 = (1 << 23) - 1
B = 0.12                                                 # analog curve bias (even harmonics; the DC blocker takes the offset)
TH = 0.5                                                 # soft-clipper knee
N = 2049                                                 # table over v in [-16, 16] full scale, step 1/64


def sstep(x):
    x = min(1.0, max(0.0, x))
    return x * x * (3 - 2 * x)


def analog(v):
    return CEIL * (math.tanh(v + B) - math.tanh(B)) / (1 + math.tanh(B))


def soft(v):
    a = abs(v)
    y = a if a <= TH else TH + (CEIL - TH) * math.tanh((a - TH) / (CEIL - TH))
    return math.copysign(y, v)


def knob_to_pos(k):
    if k <= KNOB_LO:
        g = -100.0
    elif k >= KNOB_HI:
        g = 100.0
    elif k < KNOB_C - KNOB_DEAD:
        g = -100.0 * (KNOB_C - KNOB_DEAD - k) / (KNOB_C - KNOB_DEAD - KNOB_LO)
    elif k <= KNOB_C + KNOB_DEAD:
        g = 0.0
    else:
        g = 100.0 * (k - KNOB_C - KNOB_DEAD) / (KNOB_HI - KNOB_C - KNOB_DEAD)
    return int(round(g)) + 100


def main(out):
    P, WL, WS = [], [], []
    for pos in range(201):
        g = pos - 100
        if g <= 0:
            a = (100 + g) / 100.0
            P.append(int(round(a * a * 2048)))               # Q11, unity = 2048
            WL.append(256)
            WS.append(0)
        else:
            t = g / 100.0
            P.append(int(round(10 ** (DRIVE_DB_MAX * t / 20) * 2048)))
            wl = int(round(256 * (1 - sstep(t / 0.06))))
            ws = int(round((256 - wl) * sstep((t - 0.65) / 0.35)))
            WL.append(wl)
            WS.append(ws)
    A = [int(round(analog((i - 1024) / 64.0) * (1 << 23))) for i in range(N)]
    S = [int(round(soft((i - 1024) / 64.0) * (1 << 23))) for i in range(N)]
    assert max(abs(x) for x in A + S) <= int(CEIL * (1 << 23)) + 1
    assert max(P) < 32768
    K = [knob_to_pos(k) for k in range(256)]

    def arr(name, typ, vals, per=12):
        s = f"const {typ} {name}[{len(vals)}] = {{\n"
        for i in range(0, len(vals), per):
            s += "    " + ", ".join(str(v) for v in vals[i:i + per]) + ",\n"
        return s + "};\n\n"

    with open(out, "w") as f:
        f.write("/* generated by gen_tables.py - do not edit */\n#include \"ofp_gain_dsp.h\"\n\n")
        f.write(f"const int32_t ofp_gain_ceiling = {int(round(CEIL * Q23))};   /* {CEIL_DB} dBFS, Q23 */\n\n")
        f.write(arr("ofp_gain_p", "uint16_t", P))
        f.write(arr("ofp_gain_wl", "uint16_t", WL))
        f.write(arr("ofp_gain_ws", "uint16_t", WS))
        f.write(arr("ofp_gain_knob", "uint8_t", K, 16))
        f.write(arr("ofp_gain_a", "int32_t", A, 8))
        f.write(arr("ofp_gain_s", "int32_t", S, 8))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "ofp_gain_tab.c")
